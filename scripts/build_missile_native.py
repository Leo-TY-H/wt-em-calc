"""Build the native missile flight model (C core + thin Cython wrapper).

The C sources in scripts/missile_native port scripts/missile_model with the
same binary32 operation order. Numerical tables are generated from the hashed
model resources at build time. Compilation uses strict IEEE evaluation without
contraction so float32 results match the reference bit for bit.
"""
import hashlib
import json
import os
from pathlib import Path
import platform
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'scripts/missile_native'
MODEL = ROOT / 'scripts/missile_model'
DIRECTORY = ROOT / '.native_missile_core'
RESOURCES = ('atan2f-table.json', 'tanf-constants.json', 'motor-deviation-table.json', 'launch-spread-table.json')


def sources():
    return sorted(p for p in SOURCE.iterdir() if p.suffix in ('.h', '.c', '.pyx', '.pxd', '.pxi'))


def signature():
    digest = hashlib.sha256()
    digest.update(('%s|%s|%s|%s' % (sys.version, sys.platform, platform.machine(), sys.implementation.cache_tag)).encode())
    digest.update(Path(__file__).read_bytes())
    for path in sources():
        digest.update(path.name.encode()); digest.update(path.read_bytes())
    for name in RESOURCES:
        digest.update((MODEL / name).read_bytes())
    return digest.hexdigest()


def tables_header():
    sys.path.insert(0, str(MODEL))
    import native_atan2f, native_tanf, motor_vector
    lines = ['/* Generated by build_missile_native.py from hashed model resources. */',
             '#ifndef WTM_TABLES_H', '#define WTM_TABLES_H']
    lines.append('static const double ATAN2F_TABLE[%d] = {%s};' % (len(native_atan2f.TABLE), ','.join(repr(float(v)) for v in native_atan2f.TABLE)))
    names = dict(QUARTER_PI=0x147541438, SMALL=0x147541400, CUBIC=0x147541408, LARGE=0x1475413e8, THIRD=0x1475413f8,
                 TWO_OVER_PI=0x147541380, PI2_HEAD=0x147541418, PI2_TAIL=0x147541420, HALF_PI=0x147541428,
                 P0=0x1475413c0, P1=0x1475413c8, Q0=0x1475413d0, Q1=0x1475413d8, Q2=0x1475413e0)
    for name, address in names.items():
        value = struct.unpack('<d', native_tanf.DATA[address][:8])[0]
        lines.append('#define TANF_%s (%s)' % (name, repr(value)))
    lines.append('static const unsigned char TANF_TABLE[%d] = {%s};' % (len(native_tanf.TABLE), ','.join(str(b) for b in native_tanf.TABLE)))
    rows = motor_vector.TABLE
    lines.append('static const float MOTOR_DEVIATION_TABLE[%d][2] = {%s};' % (len(rows), ','.join('{%r,%r}' % (float(a), float(b)) for a, b in rows)))
    lines.append('#endif')
    return '\n'.join(lines) + '\n'


def build():
    from Cython.Build import cythonize
    from setuptools import Extension, setup
    DIRECTORY.mkdir(exist_ok=True)
    generated = DIRECTORY / 'generated'; generated.mkdir(exist_ok=True)
    (generated / 'tables.h').write_text(tables_header(), encoding='utf-8')
    tag = signature()
    library = DIRECTORY / ('lib-' + tag[:16])
    flags = ['/O2', '/fp:strict', '/fp:except-'] if os.name == 'nt' else ['-O2', '-ffp-contract=off', '-fno-fast-math', '-fno-finite-math-only']
    # Compile a copy beside the generated header: short paths for MSVC.
    wrapper = DIRECTORY / '_missile_native.pyx'
    wrapper.write_bytes((SOURCE / 'wtm.pyx').read_bytes())
    extension = Extension('_missile_native', [str(wrapper)], include_dirs=[str(SOURCE), str(generated)],
                          extra_compile_args=flags)
    modules = cythonize([extension], compiler_directives={'language_level': 3, 'boundscheck': False, 'wraparound': False,
                                                          'cdivision': True, 'infer_types': False})
    setup(name='missile-native', ext_modules=modules,
          script_args=['build_ext', '--build-lib', str(library), '--build-temp', str(DIRECTORY / 'objects')])
    binaries = {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in library.iterdir() if p.suffix in ('.pyd', '.so')}
    if len(binaries) != 1: raise RuntimeError('Missing native missile extension')
    manifest = dict(signature=tag, library=library.name, binaries=binaries, compiler_flags=flags)
    temporary = DIRECTORY / 'manifest.tmp'
    temporary.write_text(json.dumps(manifest, indent=2), encoding='utf-8')
    temporary.replace(DIRECTORY / 'manifest.json')
    return library


def load(required=False):
    """Import the verified native module, or None when it is missing or stale."""
    import importlib.util
    try:
        manifest = json.loads((DIRECTORY / 'manifest.json').read_text())
        if manifest['signature'] != signature(): raise ValueError('Native missile model source/ABI mismatch')
        library = manifest['library']
        if Path(library).name != library: raise ValueError('Invalid native library directory')
        (name, digest), = manifest['binaries'].items()
        path = DIRECTORY / library / name
        if Path(name).name != name or hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            raise ValueError('Native missile model hash mismatch')
        if '_missile_native' in sys.modules: return sys.modules['_missile_native']
        spec = importlib.util.spec_from_file_location('_missile_native', path)
        module = importlib.util.module_from_spec(spec)
        sys.modules['_missile_native'] = module
        spec.loader.exec_module(module)
        return module
    except (OSError, ValueError, KeyError, TypeError, ImportError):
        if required: raise
        return None


if __name__ == '__main__':
    print(build())
